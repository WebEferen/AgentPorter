"""Generate src/unicode_tables.rs: where Python's str predicates differ from Rust std's char predicates.

Run from the crate root with the CPython whose behavior the fixtures record:
    python3 -I .porter/tools/gen_unicode_tables.py src/unicode_tables.rs
It compiles a small Rust program with the local rustc to dump std's view, then runs rustfmt on the output.
"""

import os
import platform
import subprocess
import sys
import tempfile
import unicodedata

DUMP_RS = r"""
fn main() {
    println!("version {}.{}.{}", char::UNICODE_VERSION.0, char::UNICODE_VERSION.1, char::UNICODE_VERSION.2);
    let preds: [(&str, fn(char) -> bool); 3] =
        [("upper", char::is_uppercase), ("lower", char::is_lowercase), ("numeric", char::is_numeric)];
    for c in (0..=0x10FFFFu32).filter_map(char::from_u32) {
        for (name, f) in preds {
            if f(c) {
                println!("{name} {:x}", c as u32);
            }
        }
    }
}
"""

CODEPOINTS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def std_sets() -> tuple[str, dict[str, set[int]]]:
    with tempfile.TemporaryDirectory() as tmp:
        src, exe = os.path.join(tmp, "dump.rs"), os.path.join(tmp, "dump")
        with open(src, "w", encoding="utf-8") as f:
            f.write(DUMP_RS)
        subprocess.run(["rustc", "--edition", "2021", "-O", "-o", exe, src], check=True)
        out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    rustc = subprocess.run(["rustc", "--version"], check=True, capture_output=True, text=True).stdout.split()[1]
    sets: dict[str, set[int]] = {"upper": set(), "lower": set(), "numeric": set()}
    version = ""
    for line in out.splitlines():
        name, value = line.split()
        if name == "version":
            version = value
        else:
            sets[name].add(int(value, 16))
    return f"rustc {rustc} (char::UNICODE_VERSION {version})", sets


def ranges(points: set[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in sorted(points):
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def table(name: str, doc: str, points: set[int]) -> str:
    rows = "".join(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),\n" for a, b in ranges(points))
    return f"/// {doc}\npub(crate) static {name}: &[(char, char)] = &[\n{rows}];\n"


def main() -> None:
    std_version, std = std_sets()
    py = {
        "upper": {c for c in CODEPOINTS if chr(c).isupper()},
        "lower": {c for c in CODEPOINTS if chr(c).islower()},
        "numeric": {c for c in CODEPOINTS if chr(c).isnumeric()},
    }
    title = {c for c in CODEPOINTS if unicodedata.category(chr(c)) == "Lt"}
    # py_isupper loops without CPython's one-character special case; that is only sound if no
    # character is uppercase and also lowercase or titlecase.
    assert not py["upper"] & (py["lower"] | title), "py_isupper needs CPython's length-1 special case"
    py_version = f"CPython {platform.python_version()} (unicodedata {unicodedata.unidata_version})"
    parts = [
        "//! Where Python's `str` predicates differ from Rust std's `char` predicates.\n"
        "//!\n"
        f"//! Generated by `python3 -I .porter/tools/gen_unicode_tables.py` from {py_version}\n"
        f"//! against {std_version}. Do not edit by hand. Ranges are inclusive and sorted.\n",
        table("TITLECASE", "General_Category Lt (CPython's TITLE_MASK); std has no titlecase predicate.", title),
    ]
    for key, method in (("upper", "isupper"), ("lower", "islower"), ("numeric", "isnumeric")):
        rust = {"upper": "is_uppercase", "lower": "is_lowercase", "numeric": "is_numeric"}[key]
        parts.append(table(f"{key.upper()}_PY_ONLY", f"`str.{method}` is true and `char::{rust}` is false.",
                           py[key] - std[key]))
        parts.append(table(f"{key.upper()}_STD_ONLY", f"`char::{rust}` is true and `str.{method}` is false.",
                           std[key] - py[key]))
    path = sys.argv[1]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    subprocess.run(["rustfmt", "--edition", "2021", path], check=True)
    for key in py:
        print(f"{key}: {len(py[key] - std[key])} python-only, {len(std[key] - py[key])} std-only")
    print(f"titlecase: {len(title)}")


if __name__ == "__main__":
    main()
