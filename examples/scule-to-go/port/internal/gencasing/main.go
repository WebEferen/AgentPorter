//go:build ignore

// Command gencasing writes casing_table.go: the full case mappings of
// JavaScript's toUpperCase and toLowerCase that expand one code point into
// several (Unicode SpecialCasing.txt, unconditional entries). It asks Node.js
// for the mapping of every code point, so the table follows the Unicode
// version of the node on PATH.
//
// Run from the module root:
//
//	go run ./internal/gencasing/main.go
//
// It also reports, on stderr, code points whose single-code-point mapping
// differs between Node.js and Go's unicode package. Those come from a newer
// Unicode version in Node.js and are not part of the table.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strconv"
	"unicode"
)

const dumpScript = `
const out = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const s = String.fromCodePoint(c);
  const u = s.toUpperCase(), l = s.toLowerCase();
  if (u !== s || l !== s) out.push([c, u, l]);
}
process.stdout.write(JSON.stringify({node: process.version, unicode: process.versions.unicode, rows: out}));
`

type dump struct {
	Node    string               `json:"node"`
	Unicode string               `json:"unicode"`
	Rows    [][3]json.RawMessage `json:"rows"`
}

type entry struct {
	r       rune
	mapping string
}

func main() {
	out, err := exec.Command("node", "-e", dumpScript).Output()
	if err != nil {
		log.Fatalf("gencasing: node: %v", err)
	}
	var d dump
	if err := json.Unmarshal(out, &d); err != nil {
		log.Fatalf("gencasing: %v", err)
	}
	var upper, lower []entry
	versionDeltas := 0
	for _, row := range d.Rows {
		var c rune
		var u, l string
		if json.Unmarshal(row[0], &c) != nil || json.Unmarshal(row[1], &u) != nil || json.Unmarshal(row[2], &l) != nil {
			log.Fatalf("gencasing: bad row %s", row)
		}
		for _, m := range []struct {
			js     string
			simple rune
			table  *[]entry
		}{{u, unicode.ToUpper(c), &upper}, {l, unicode.ToLower(c), &lower}} {
			switch n := len([]rune(m.js)); {
			case n > 1:
				*m.table = append(*m.table, entry{c, m.js})
			case m.js != string(m.simple):
				versionDeltas++
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/gencasing/main.go; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: Node.js %s (Unicode %s).\n\npackage scule\n\n", d.Node, d.Unicode)
	writeTable(&b, "specialUpper", "uppercase", "unicode.ToUpper", upper)
	b.WriteString("\n")
	writeTable(&b, "specialLower", "lowercase", "unicode.ToLower", lower)
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gencasing: %v", err)
	}
	if err := os.WriteFile("casing_table.go", src, 0o644); err != nil {
		log.Fatalf("gencasing: %v", err)
	}
	fmt.Fprintf(os.Stderr, "gencasing: %d uppercase and %d lowercase entries; %d single-code-point mappings differ from Go's unicode %s (newer Unicode in Node.js, not in the table)\n",
		len(upper), len(lower), versionDeltas, unicode.Version)
}

func writeTable(b *bytes.Buffer, name, kind, simple string, entries []entry) {
	fmt.Fprintf(b, "// %s maps a code point to its full %s mapping where that mapping has\n", name, kind)
	fmt.Fprintf(b, "// more than one code point. Every other code point uses %s.\n", simple)
	fmt.Fprintf(b, "var %s = map[rune]string{\n", name)
	for _, e := range entries {
		fmt.Fprintf(b, "\t0x%04X: %s, // %c\n", e.r, strconv.QuoteToASCII(e.mapping), e.r)
	}
	b.WriteString("}\n")
}
